#pragma once

#include <cstdint>

#include "ceio/net/traffic.hpp"
#include "ceio/sim/simulator.hpp"

namespace ceio::net {

struct DctcpConfig {
  bool enabled = false;
  Tick rtt = 20 * kMicrosecond;        ///< control interval (one window per RTT)
  Tick feedback_delay = 5 * kMicrosecond;  ///< receiver -> sender ACK latency
  double g = 1.0 / 16;                 ///< alpha EWMA gain (DCTCP paper)
  /// Additive increase per RTT without marks, in packets (DCTCP: 1 MSS per RTT).
  double additive_packets = 1.0;
  double min_gbps = 0.1;
};

/// Rate-based DCTCP for one flow ([CEIO] Sec. 2.3 uses DCTCP as the network CCA).
///
/// Per RTT window the controller counts ACKs, ECN-echoed ACKs and losses.
/// With marks: alpha <- (1-g) alpha + g F and rate <- rate (1 - alpha/2); a loss
/// halves the rate (once per window). Without marks the rate grows additively,
/// capped at the application's demand (the flow's configured rate).
class DctcpController {
 public:
  DctcpController(Simulator& sim, TrafficSource& src, const DctcpConfig& cfg);
  void start();

  /// The receiver application consumed a packet; `ecn` is its CE mark.
  void on_delivered(bool ecn);
  /// A packet of this flow was dropped (switch or NIC).
  void on_lost();
  /// Congestion notification generated by the receiver NIC itself (RoCE CNP style),
  /// counted as a marked ACK without waiting for the data to be delivered.
  void on_notification();

  double alpha() const { return alpha_; }
  std::uint64_t reductions() const { return reductions_; }

 private:
  void window();
  Simulator& sim_;
  TrafficSource& src_;
  DctcpConfig cfg_;
  double demand_;
  double additive_gbps_;
  double alpha_ = 0.0;
  std::uint64_t acked_ = 0, marked_ = 0, lost_ = 0;
  std::uint64_t reductions_ = 0;
};

}  // namespace ceio::net
